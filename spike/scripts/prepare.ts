// Joins the seed CSVs into spike/data/*.ts so the Vercel function never reads ../seed.
import { readFileSync, writeFileSync } from 'node:fs';
import type { GoldenEvent, SpikeVc } from '../lib/types.js';

function parseCsv(text: string): Record<string, string>[] {
  const rows: string[][] = [];
  let row: string[] = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field.replace(/\r$/, '')); rows.push(row); row = []; field = ''; }
    else field += c;
  }
  if (field || row.length) { row.push(field.replace(/\r$/, '')); rows.push(row); }
  const header = rows.shift()!;
  return rows.filter((r) => r.some((v) => v.trim())).map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ''])));
}

const read = (p: string) => parseCsv(readFileSync(new URL(`../../seed/${p}`, import.meta.url), 'utf8'));
const norm = (s: string) => s.trim().toLowerCase().replace(/\s+/g, ' ');
const slug = (s: string) => norm(s).replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const list = (s: string) => s.split(';').map((x) => x.trim()).filter(Boolean);

const master = read('vcs_import_master.csv');
const profiles = read('vc_profile_seed.csv');
const firms = read('firms_seed.csv');

const unmatched: string[] = [];
const vcs: SpikeVc[] = master.map((m) => {
  const p = profiles.find((r) => norm(r.name) === norm(m.name) && norm(r.firm) === norm(m.firm));
  const f = firms.find((r) => norm(r.firm) === norm(m.firm) || list(r.firm_aliases).some((a) => norm(a) === norm(m.firm)));
  if (!p) unmatched.push(`profile: ${m.name} / ${m.firm}`);
  if (!f) unmatched.push(`firm: ${m.firm}`);
  const tier = p?.tier ? Number(p.tier) : NaN;
  return {
    id: `${slug(m.name)}--${slug(m.firm)}`,
    name: m.name.trim(),
    firm: m.firm.trim(),
    aliases: p ? list(p.aliases) : [],
    firmAliases: f ? list(f.firm_aliases) : [],
    ambiguous: p?.ambiguous_name === 'True',
    trust: p?.trust ?? '',
    tier: Number.isFinite(tier) ? tier : null,
    rssUrl: m.rss_url?.trim() || null,
    firmRss: f?.firm_rss?.trim() || null,
  };
});

if (unmatched.length) {
  console.error('Unmatched seed rows (not guessing):\n  ' + unmatched.join('\n  '));
  process.exit(1);
}

const golden = JSON.parse(readFileSync(new URL('../../seed/golden_events.json', import.meta.url), 'utf8'));
const events: GoldenEvent[] = golden.events.map((e: GoldenEvent) => ({
  id: e.id, company: e.company, firm: e.firm, tracked_vc: e.tracked_vc,
  expected_types: e.expected_types, competitor_under_default_persona: e.competitor_under_default_persona,
}));

const header = '// GENERATED by spike/scripts/prepare.ts from /seed. Do not edit.\n';
writeFileSync(new URL('../data/vcs.ts', import.meta.url),
  `${header}import type { SpikeVc } from '../lib/types.js';\nexport const VCS: SpikeVc[] = ${JSON.stringify(vcs, null, 2)};\n`);
writeFileSync(new URL('../data/golden.ts', import.meta.url),
  `${header}import type { GoldenEvent } from '../lib/types.js';\nexport const GOLDEN: GoldenEvent[] = ${JSON.stringify(events, null, 2)};\n`);
console.log(`Wrote ${vcs.length} VCs (${vcs.filter((v) => v.ambiguous).length} ambiguous) and ${events.length} golden events.`);
